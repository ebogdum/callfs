#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 -v runtime_password="$CALLFS_POSTGRES_RUNTIME_PASSWORD" --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'EOSQL'
CREATE ROLE callfs_app LOGIN PASSWORD :'runtime_password';
GRANT CONNECT ON DATABASE callfs TO callfs_app;
GRANT USAGE ON SCHEMA public TO callfs_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO callfs_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE ON SEQUENCES TO callfs_app;
EOSQL
